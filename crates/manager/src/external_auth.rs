pub const MAX_GRANTS: usize = 256;
pub const MAX_TTL: Duration = Duration::from_secs(30 * 24 * 60 * 60);

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Error {
    Unauthorized,
    InvalidInput,
    Expired,
    Revoked,
    ProjectMismatch,
    RevisionConflict,
    Capacity,
    StorageUnavailable,
    EntropyUnavailable,
    ClockUnavailable,
}
impl std::fmt::Display for Error {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(match self {
            Self::Unauthorized => "external_grant_unauthorized",
            Self::InvalidInput => "external_grant_invalid_input",
            Self::Expired => "external_grant_expired",
            Self::Revoked => "external_grant_revoked",
            Self::ProjectMismatch => "external_grant_project_mismatch",
            Self::RevisionConflict => "external_grant_revision_conflict",
            Self::Capacity => "external_grant_capacity",
            Self::StorageUnavailable => "external_grant_storage_unavailable",
            Self::EntropyUnavailable => "external_grant_entropy_unavailable",
            Self::ClockUnavailable => "external_grant_clock_unavailable",
        })
    }
}
impl std::error::Error for Error {}
pub type Result<T> = std::result::Result<T, Error>;

/// Internal policy additions, not yet public tool/schema capabilities.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum InformationScope {
    LogContent,
    InspectorQueries,
    MailContent,
    SourceArtifacts,
    DatabaseQuery,
}

/// High-entropy bearer credential. No Clone/Serialize or plaintext Debug.
pub struct ExternalCredential(Zeroizing<String>);
impl ExternalCredential {
    /// Parsing establishes no authority. Enforce transport bounds before this.
    pub fn from_wire(value: &str) -> Result<Self> {
        if !valid_digest(value) {
            return Err(Error::Unauthorized);
        }
        Ok(Self(Zeroizing::new(value.to_owned())))
    }
    /// Only for the explicit trusted issuance/private transport boundary.
    /// Never put this in argv, environment, diagnostics or ordinary tool results.
    pub fn expose_secret(&self) -> &str {
        &self.0
    }
}
impl std::fmt::Debug for ExternalCredential {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str("ExternalCredential([REDACTED])")
    }
}

#[derive(Debug, Clone, Serialize)]
pub struct GrantRecord {
    pub grant_id: Id,
    /// Generated by the manager, stable for this credential across restarts.
    pub client_id: Id,
    pub project_id: Id,
    pub scopes: Vec<Scope>,
    pub information: Vec<InformationScope>,
    pub created_at: u64,
    pub expires_at: u64,
    pub revoked: bool,
    pub expired: bool,
}
#[derive(Debug)]
pub struct IssuedGrant {
    pub record: GrantRecord,
    pub credential: ExternalCredential,
}

/// A single completed check, not a native authority or durable execution grant.
/// Future adapters must authorize again at actual admission/dequeue boundaries.
#[derive(Debug)]
pub struct AuthorizedExternal {
    client_id: Id,
    grant_id: Id,
    project_id: Id,
    revision: u64,
    expires_at: u64,
}
impl AuthorizedExternal {
    pub fn client_id(&self) -> &Id {
        &self.client_id
    }
    pub fn grant_id(&self) -> &Id {
        &self.grant_id
    }
    pub fn project_id(&self) -> &Id {
        &self.project_id
    }
    pub fn revision(&self) -> u64 {
        self.revision
    }
    pub fn expires_at(&self) -> u64 {
        self.expires_at
    }
}

trait Clock: Send + Sync {
    fn now(&self) -> Result<u64>;
}
struct SystemClock;
impl Clock for SystemClock {
    fn now(&self) -> Result<u64> {
        SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .ok()
            .and_then(|value| value.as_millis().try_into().ok())
            .filter(|value| *value <= i64::MAX as u64)
            .ok_or(Error::ClockUnavailable)
    }
}

pub struct ExternalRegistry {
    endpoint: Endpoint,
    owner_user: String,
    root_identity: String,
    db: Connection,
    _file: File,
    clock: Arc<dyn Clock>,
    // Last field: SQLite and its checked file close before final owner release.
    _owner: crate::endpoint::OwnerGuard,
}
struct Stored {
    record: GrantRecord,
    root_identity: String,
    token_hash: String,
}
impl ExternalRegistry {
    /// Owner construction/SQLite only; never reads or provisions native secrets.
    /// Run on a bounded storage worker rather than the transport event loop.
    pub fn open(owner: &Owner) -> Result<Self> {
        Self::open_with_clock(owner, Arc::new(SystemClock))
    }
    fn open_with_clock(owner: &Owner, clock: Arc<dyn Clock>) -> Result<Self> {
        let endpoint = owner.endpoint().clone();
        endpoint.validate().map_err(|_| Error::StorageUnavailable)?;
        let owner_user = crate::transport::os::current_user().map_err(|_| Error::Unauthorized)?;
        let root_identity = path_identity(endpoint.root())?;
        let path = endpoint.directory.join("external-grants.sqlite3");
        for suffix in ["", "-journal", "-wal", "-shm"] {
            let mut sibling = path.as_os_str().to_os_string();
            sibling.push(suffix);
            if fs::symlink_metadata(&sibling).is_ok() {
                let mut options = OpenOptions::new();
                options.read(true).write(true);
                crate::transport::os::secure_lock_options(&mut options);
                let file = options
                    .open(&sibling)
                    .map_err(|_| Error::StorageUnavailable)?;
                crate::transport::os::validate_lock(&file)
                    .map_err(|_| Error::StorageUnavailable)?;
            }
        }
        let mut options = OpenOptions::new();
        options.read(true).write(true).create(true).truncate(false);
        crate::transport::os::secure_lock_options(&mut options);
        let file = options.open(&path).map_err(|_| Error::StorageUnavailable)?;
        crate::transport::os::validate_lock(&file).map_err(|_| Error::StorageUnavailable)?;
        let db = Connection::open_with_flags(
            path,
            OpenFlags::SQLITE_OPEN_READ_WRITE | OpenFlags::SQLITE_OPEN_NOFOLLOW,
        )
        .map_err(|_| Error::StorageUnavailable)?;
        db.busy_timeout(Duration::from_millis(250))
            .map_err(storage)?;
        let version: u32 = db
            .pragma_query_value(None, "user_version", |row| row.get(0))
            .map_err(storage)?;
        if version > 2 {
            return Err(Error::StorageUnavailable);
        }
        db.execute_batch("PRAGMA journal_mode=DELETE; PRAGMA synchronous=FULL;")
            .map_err(storage)?;
        if version == 0 {
            db.execute_batch("BEGIN IMMEDIATE; CREATE TABLE registry_identity(singleton INTEGER PRIMARY KEY CHECK(singleton=1),root_identity TEXT NOT NULL,owner_hash TEXT NOT NULL,high_water INTEGER NOT NULL); CREATE TABLE grants(grant_id TEXT PRIMARY KEY,client_id TEXT NOT NULL UNIQUE,project_id TEXT NOT NULL,root_identity TEXT NOT NULL,token_hash TEXT NOT NULL UNIQUE,scopes TEXT NOT NULL,information TEXT NOT NULL,created_at INTEGER NOT NULL,expires_at INTEGER NOT NULL,revoked INTEGER NOT NULL CHECK(revoked IN (0,1)),expired INTEGER NOT NULL CHECK(expired IN (0,1))); PRAGMA user_version=1;").map_err(storage)?;
            db.execute(
                "INSERT INTO registry_identity VALUES(1,?1,?2,0)",
                params![root_identity, digest(owner_user.as_bytes())],
            )
            .map_err(storage)?;
            db.execute_batch("COMMIT;").map_err(storage)?;
        }
        let stored: (String, String) = db
            .query_row(
                "SELECT root_identity,owner_hash FROM registry_identity WHERE singleton=1",
                [],
                |row| Ok((row.get(0)?, row.get(1)?)),
            )
            .map_err(storage)?;
        if stored != (root_identity.clone(), digest(owner_user.as_bytes())) {
            return Err(Error::StorageUnavailable);
        }
        if version < 2 {
            // Additive v1 migration: all grant identities, hashes, rights,
            // expiry/revocation rows and the durable high-water remain intact.
            db.execute_batch("BEGIN IMMEDIATE; ALTER TABLE registry_identity ADD COLUMN clock_fault INTEGER NOT NULL DEFAULT 0 CHECK(clock_fault IN (0,1)); PRAGMA user_version=2; COMMIT;").map_err(storage)?;
        }
        Ok(Self {
            endpoint,
            owner_user,
            root_identity,
            db,
            _file: file,
            clock,
            _owner: owner.retain_lease(),
        })
    }
    fn check_root(&self) -> Result<()> {
        self.endpoint
            .validate()
            .map_err(|_| Error::StorageUnavailable)?;
        if path_identity(self.endpoint.root())? != self.root_identity {
            return Err(Error::StorageUnavailable);
        }
        Ok(())
    }
    fn check_desktop(&self, authority: &DesktopAuthority<'_>) -> Result<()> {
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        if authority.root() != self.endpoint.root() || authority.peer().user != self.owner_user {
            return Err(Error::Unauthorized);
        }
        self.check_root()
    }
    /// Explicit trusted consent only. No client-supplied identity/token is accepted.
    pub fn issue(
        &mut self,
        authority: &DesktopAuthority<'_>,
        project: &ProjectBinding,
        scopes: &[Scope],
        information: &[InformationScope],
        ttl: Duration,
    ) -> Result<IssuedGrant> {
        self.check_desktop(authority)?;
        validate_rights(scopes, information)?;
        if ttl.is_zero() || ttl > MAX_TTL || ttl.as_millis() == 0 {
            return Err(Error::InvalidInput);
        }
        let project_identity = path_identity(project.root())?;
        let credential = ExternalCredential(random_secret()?);
        let grant_id = random_id("eg-")?;
        let client_id = random_id("ec-")?;
        let clock = self.clock.clone();
        let transaction = self
            .db
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(storage)?;
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        let now = match advance_clock(&transaction, clock.now()) {
            Ok(now) => now,
            Err(Error::ClockUnavailable) => {
                // No grant has been inserted. Persist this deny-only security
                // observation even if the admitted desktop proof just expired.
                let permission = authority
                    .check_current(Instant::now())
                    .map_err(|_| Error::Unauthorized);
                transaction.commit().map_err(storage)?;
                permission?;
                return Err(Error::ClockUnavailable);
            }
            Err(error) => return Err(error),
        };
        let count: i64 = transaction
            .query_row("SELECT count(*) FROM grants", [], |row| row.get(0))
            .map_err(storage)?;
        if count >= MAX_GRANTS as i64 {
            return Err(Error::Capacity);
        }
        let expires_at = now
            .checked_add(ttl.as_millis() as u64)
            .filter(|value| *value <= i64::MAX as u64)
            .ok_or(Error::InvalidInput)?;
        let record = GrantRecord {
            grant_id,
            client_id,
            project_id: project.project_id().clone(),
            scopes: scopes.to_vec(),
            information: information.to_vec(),
            created_at: now,
            expires_at,
            revoked: false,
            expired: false,
        };
        transaction
            .execute(
                "INSERT INTO grants VALUES(?1,?2,?3,?4,?5,?6,?7,?8,?9,0,0)",
                params![
                    record.grant_id.as_str(),
                    record.client_id.as_str(),
                    record.project_id.as_str(),
                    project_identity,
                    digest(credential.expose_secret().as_bytes()),
                    serde_json::to_string(scopes).map_err(|_| Error::InvalidInput)?,
                    serde_json::to_string(information).map_err(|_| Error::InvalidInput)?,
                    now as i64,
                    expires_at as i64
                ],
            )
            .map_err(storage)?;
        // SQL waits must not turn an expired desktop proof into an issuer.
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        if path_identity(project.root())? != project_identity {
            return Err(Error::ProjectMismatch);
        }
        transaction.commit().map_err(storage)?;
        Ok(IssuedGrant { record, credential })
    }
    /// Durable, idempotent revocation. It does not cancel an already running job.
    pub fn revoke(&mut self, authority: &DesktopAuthority<'_>, grant: &Id) -> Result<()> {
        self.check_desktop(authority)?;
        let transaction = self
            .db
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(storage)?;
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        if transaction
            .execute(
                "UPDATE grants SET revoked=1 WHERE grant_id=?1",
                [grant.as_str()],
            )
            .map_err(storage)?
            != 1
        {
            return Err(Error::Unauthorized);
        }
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        transaction.commit().map_err(storage)
    }
    /// Stored last-observation status, not proof of a currently usable grant.
    /// Only authorization/issuance/listing observes and latches a bad clock.
    pub fn clock_status(&self, authority: &DesktopAuthority<'_>) -> Result<ClockStatus> {
        self.check_desktop(authority)?;
        let state = read_clock(&self.db)?;
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        Ok(state)
    }
    /// Explicit native-owner recovery, never automatic and never caller time.
    /// All old credentials remain revoked even after the wall clock catches up.
    pub fn recover_clock(
        &mut self,
        authority: &DesktopAuthority<'_>,
        _action: &TrustedDesktopAction,
    ) -> Result<usize> {
        self.check_desktop(authority)?;
        let clock = self.clock.clone();
        let transaction = self
            .db
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(storage)?;
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        let now = clock.now()?;
        if !valid_clock(now) {
            return Err(Error::ClockUnavailable);
        }
        let revoked = transaction
            .execute("UPDATE grants SET revoked=1 WHERE revoked=0", [])
            .map_err(storage)?;
        if transaction
            .execute(
                "UPDATE registry_identity SET high_water=?1,clock_fault=0 WHERE singleton=1",
                [now as i64],
            )
            .map_err(storage)?
            != 1
        {
            return Err(Error::StorageUnavailable);
        }
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        transaction.commit().map_err(storage)?;
        Ok(revoked)
    }
    /// Bounded owner-only metadata, never a token/root-path/content export.
    pub fn list(&mut self, authority: &DesktopAuthority<'_>) -> Result<Vec<GrantRecord>> {
        self.check_desktop(authority)?;
        let clock = self.clock.clone();
        let transaction = self
            .db
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(storage)?;
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        let now = observe_owner_clock(&transaction, clock.now())?;
        let (transaction, now) = if read_clock(&transaction)?.fault_latched {
            // This transaction contains only deny-only clock metadata, never a
            // new grant. Commit before listing/decoding any protected records.
            let permission = authority
                .check_current(Instant::now())
                .map_err(|_| Error::Unauthorized);
            transaction.commit().map_err(storage)?;
            permission?;
            let next = self
                .db
                .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
                .map_err(storage)?;
            authority
                .check_current(Instant::now())
                .map_err(|_| Error::Unauthorized)?;
            // A concurrently explicit owner recovery may have reset the stored
            // baseline. Use that current administrative snapshot, not stale time.
            let now = read_clock(&next)?.high_water;
            (next, now)
        } else {
            (transaction, now)
        };
        transaction
            .execute(
                "UPDATE grants SET expired=1 WHERE expires_at<=?1",
                [now as i64],
            )
            .map_err(storage)?;
        let records = {
            let mut statement = transaction.prepare("SELECT grant_id,client_id,project_id,root_identity,token_hash,scopes,information,created_at,expires_at,revoked,expired FROM grants ORDER BY grant_id LIMIT 257").map_err(storage)?;
            let rows = statement.query_map([], read_stored).map_err(storage)?;
            rows.map(|row| decode(row.map_err(storage)?).map(|stored| stored.record))
                .collect::<Result<Vec<_>>>()?
        };
        if records.len() > MAX_GRANTS {
            return Err(Error::StorageUnavailable);
        }
        authority
            .check_current(Instant::now())
            .map_err(|_| Error::Unauthorized)?;
        transaction.commit().map_err(storage)?;
        Ok(records)
    }
    /// Kernel peer and current registry binding are trusted adapter inputs.
    /// No client ID, root, role, or clock value is accepted from request data.
    pub fn authorize(
        &mut self,
        peer: &PeerIdentity,
        credential: &ExternalCredential,
        project: &ProjectBinding,
        required: &[Scope],
        information: &[InformationScope],
        expected_revision: Option<u64>,
    ) -> Result<AuthorizedExternal> {
        self.check_root()?;
        if peer.user != self.owner_user {
            return Err(Error::Unauthorized);
        }
        validate_rights(required, information)?;
        let token_hash = digest(credential.expose_secret().as_bytes());
        let project_identity = path_identity(project.root())?;
        let clock = self.clock.clone();
        let transaction = self
            .db
            .transaction_with_behavior(rusqlite::TransactionBehavior::Immediate)
            .map_err(storage)?;
        let now = match advance_clock(&transaction, clock.now()) {
            Ok(now) => now,
            Err(Error::ClockUnavailable) => {
                transaction.commit().map_err(storage)?;
                return Err(Error::ClockUnavailable);
            }
            Err(error) => return Err(error),
        };
        let row = transaction.query_row("SELECT grant_id,client_id,project_id,root_identity,token_hash,scopes,information,created_at,expires_at,revoked,expired FROM grants WHERE token_hash=?1", [&token_hash], read_stored).optional().map_err(storage)?;
        let Some(row) = row else {
            transaction.commit().map_err(storage)?;
            return Err(Error::Unauthorized);
        };
        let stored = decode(row)?;
        if !bool::from(stored.token_hash.as_bytes().ct_eq(token_hash.as_bytes())) {
            return Err(Error::Unauthorized);
        }
        let record = stored.record;
        if record.revoked {
            transaction.commit().map_err(storage)?;
            return Err(Error::Revoked);
        }
        if record.expired || now >= record.expires_at {
            transaction
                .execute(
                    "UPDATE grants SET expired=1 WHERE grant_id=?1",
                    [record.grant_id.as_str()],
                )
                .map_err(storage)?;
            transaction.commit().map_err(storage)?;
            return Err(Error::Expired);
        }
        let outcome = if &record.project_id != project.project_id()
            || stored.root_identity != project_identity
            || path_identity(project.root())? != project_identity
        {
            Err(Error::ProjectMismatch)
        } else if expected_revision.is_some_and(|revision| revision != project.revision()) {
            Err(Error::RevisionConflict)
        } else if required.iter().any(|scope| !record.scopes.contains(scope))
            || information
                .iter()
                .any(|scope| !record.information.contains(scope))
        {
            Err(Error::Unauthorized)
        } else {
            Ok(AuthorizedExternal {
                client_id: record.client_id,
                grant_id: record.grant_id,
                project_id: record.project_id,
                revision: project.revision(),
                expires_at: record.expires_at,
            })
        };
        transaction.commit().map_err(storage)?;
        outcome
    }
}

fn storage(_: rusqlite::Error) -> Error {
    Error::StorageUnavailable
}
fn validate_rights(scopes: &[Scope], information: &[InformationScope]) -> Result<()> {
    if scopes.is_empty()
        || scopes.len() > 4
        || information.len() > 5
        || (!information.is_empty() && !scopes.contains(&Scope::Observer))
    {
        return Err(Error::InvalidInput);
    }
    for (index, scope) in scopes.iter().enumerate() {
        if scopes[..index].contains(scope) {
            return Err(Error::InvalidInput);
        }
    }
    for (index, scope) in information.iter().enumerate() {
        if information[..index].contains(scope) {
            return Err(Error::InvalidInput);
        }
    }
    Ok(())
}
/// Native owner metadata only. A clear latch is not grant authorization.
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize)]
pub struct ClockStatus {
    pub high_water: u64,
    pub fault_latched: bool,
}
fn read_clock(connection: &Connection) -> Result<ClockStatus> {
    let (prior, fault): (i64, i64) = connection
        .query_row(
            "SELECT high_water,clock_fault FROM registry_identity WHERE singleton=1",
            [],
            |row| Ok((row.get(0)?, row.get(1)?)),
        )
        .map_err(storage)?;
    if !matches!(fault, 0 | 1) {
        return Err(Error::StorageUnavailable);
    }
    Ok(ClockStatus {
        high_water: u64::try_from(prior).map_err(|_| Error::StorageUnavailable)?,
        fault_latched: fault == 1,
    })
}
fn record_clock(transaction: &Transaction<'_>, now: u64) -> Result<()> {
    if transaction
        .execute(
            "UPDATE registry_identity SET high_water=?1 WHERE singleton=1",
            [now as i64],
        )
        .map_err(storage)?
        != 1
    {
        return Err(Error::StorageUnavailable);
    }
    Ok(())
}
fn latch_clock(transaction: &Transaction<'_>) -> Result<()> {
    if transaction
        .execute(
            "UPDATE registry_identity SET clock_fault=1 WHERE singleton=1",
            [],
        )
        .map_err(storage)?
        != 1
    {
        return Err(Error::StorageUnavailable);
    }
    Ok(())
}
fn valid_clock(now: u64) -> bool {
    now > 0 && now <= i64::MAX as u64
}
/// Callers MUST commit a ClockUnavailable result so this security latch cannot
/// disappear through transaction rollback. Merely catching up never clears it.
fn advance_clock(transaction: &Transaction<'_>, observed: Result<u64>) -> Result<u64> {
    let state = read_clock(transaction)?;
    if state.fault_latched {
        return Err(Error::ClockUnavailable);
    }
    match observed {
        Ok(now) if valid_clock(now) && now >= state.high_water => {
            record_clock(transaction, now)?;
            Ok(now)
        }
        Ok(_) | Err(Error::ClockUnavailable) => {
            latch_clock(transaction)?;
            Err(Error::ClockUnavailable)
        }
        Err(error) => Err(error),
    }
}
/// Administrative listing only: it still records a detected clock fault, but can
/// use the last safe observation to show/revoke records. Never a dispatch clock.
fn observe_owner_clock(transaction: &Transaction<'_>, observed: Result<u64>) -> Result<u64> {
    let state = read_clock(transaction)?;
    if state.fault_latched {
        return Ok(state.high_water);
    }
    match observed {
        Ok(now) if valid_clock(now) && now >= state.high_water => {
            record_clock(transaction, now)?;
            Ok(now)
        }
        Ok(_) | Err(Error::ClockUnavailable) => {
            latch_clock(transaction)?;
            Ok(state.high_water)
        }
        Err(error) => Err(error),
    }
}
