//! Persisted external-client grants, separate from native desktop authority.
//!
//! This module exposes no transport, native credential lookup, tool dispatcher or
//! Workspace. A trusted desktop composition issues/revokes grants; a wire role,
//! client ID, project path or `confirm` boolean cannot issue one. Callers supply
//! only registry-resolved ProjectBinding values. The clock is server-owned.
//!
//! Observer permits safe metadata only. Content rights below are independent:
//! mail headers/bodies/links, SQL text/results, raw logs and source are not implied
//! by Observer. DatabaseQuery does not establish a SQL sandbox or execute code.
//! ExecutionTest, SensitiveOperation, project trust and reviewed plans remain
//! separate checks. Tool/schema exports must explicitly adopt these rights later.
//!
//! Authorization is a point-in-time observation. Revoke/expiry denies subsequent
//! checks (including a future dispatcher's dequeue check); already running jobs
//! are NOT automatically cancelled by this foundation. A dispatcher must define
//! and implement its running-job cancellation policy before exposing mutations.
